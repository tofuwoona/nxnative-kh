def patch_directory(source, destination):
    source, destination = Path(source), Path(destination)
    if destination.exists():
        raise ValueError('destination must not exist')
    blobs = {}
    for name, sha in INPUT_FILES.items():
        try: data = (source/name).read_bytes()
        except OSError as e: raise ValueError(f'missing input {name}') from e
        if hashlib.sha256(data).hexdigest() != sha:
            raise ValueError(f'exact input mismatch: {name}')
        blobs[name] = data
    blobs['main.patched.bin'] = patch_image(blobs['main.patched.bin'])
    manifest = {
        'provenance':'release-reconstructed rewritten modules; NOT original NSO',
        'input_sha256':INPUT_FILES,
        'default_flag':0,
        'flag_offset':hex(FLAG),
        'entry_offsets':[hex(x) for x in QUAD_CALLS],
        'payload_version':2,
        'preserved_producer_entries':[hex(PRODUCER),hex(PRODUCER2)],
        'geometry_policy':'authentic constructor then equalize vertex 1/2/3 X to vertex 0 X',
        'outputs':{name:{'size':len(data),'sha256':hashlib.sha256(data).hexdigest()} for name,data in blobs.items()},
    }
    destination.mkdir(parents=True)
    try:
        for name,data in blobs.items(): (destination/name).write_bytes(data)
        (destination/'bar-manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
    except BaseException:
        shutil.rmtree(destination)
        raise
    return manifest


