#!/usr/bin/env python3
"""Exact release-reconstructed rewritten KH1 image, not an original NSO.

Offline replacement of four owned persistent-bar constructor calls only. The
complete stateful producer and authentic constructor remain active. A loader-
zeroed key-page word at +0x100 controls the appended adapter and defaults OFF.
"""
import hashlib
import json
from pathlib import Path
import shutil
import struct

INPUT_SHA = '654aa3269b9d22fc94648634e114979b9441dee5bbdd681ab90937a0c2f26e53'
INPUT_SIZE = 0x31e8000
OUTPUT_SIZE = INPUT_SIZE + 0x4000
KEY_PAGE = 0x31c8000
FLAG = KEY_PAGE + 0x100
PRODUCER = 0x3edcc
PRODUCER_END = 0x3f064
PRODUCER_SHA = 'a6b634a54b44e518bf98d8082f4fb2755c88ffb3f3b22d4cbbfb7a42579500f5'
PRODUCER_PROLOGUE = bytes.fromhex('ff8302d1ed33026deb2b036de923046d')
QUAD_CONSTRUCTOR = 0x31d8c
PRODUCER2 = 0x5e940
PRODUCER2_PROLOGUE = bytes.fromhex('ff0303d1ef3b026dfb3b00f9ed33036d')
QUAD_CONSTRUCTOR2 = 0x31ea4
QUAD_CALLS1 = (0x3ef20, 0x3ef88, 0x3efd8, 0x3f024)
QUAD_CALLS2 = (0x5eb30, 0x5eb98, 0x5ebe8, 0x5ec34)
QUAD_CALLS = QUAD_CALLS1 + QUAD_CALLS2
ADAPTER = INPUT_SIZE + 0x80
ADAPTER2 = INPUT_SIZE + 0x100
PAYLOAD_SIZE = 0x100 + 56


def bl(pc, target):
    delta = target - pc
    if pc % 4 or target % 4 or not -(1 << 27) <= delta < (1 << 27):
        raise ValueError('unaligned/out-of-range AArch64 BL')
    return 0x94000000 | ((delta // 4) & 0x3ffffff)


def adrp(pc, target, reg):
    delta = (target >> 12) - (pc >> 12)
    if not -(1 << 20) <= delta < (1 << 20):
        raise ValueError('ADRP out of range')
    return 0x90000000 | reg | ((delta & 3) << 29) | (((delta >> 2) & 0x7ffff) << 5)


def adapter(pc=ADAPTER, constructor=QUAD_CONSTRUCTOR):
    # Always execute the exact authentic constructor. Restore its caller LR,
    # preserve returned x16/x17, then collapse only vertex 1/2/3 X when bit 0
    # is active. No instruction after BL changes NZCV/SIMD/FPCR/FPSR.
    words = [
        0xa9bf7bfd,                         # stp x29,x30,[sp,#-16]!
        bl(pc + 4, constructor),
        0xa8c17bfd,                         # ldp x29,x30,[sp],#16
        0xa9bf47f0,                         # stp x16,x17,[sp,#-16]!
        adrp(pc + 16, FLAG, 16),
        0xb9400210 | ((FLAG & 0xfff) // 4) << 10,
        0x36000010 | (12 - 6) << 5,        # tbz w16,#0,restore
        0xd1014011,                         # sub x17,x0,#0x50
        0xb9400230,                         # ldr w16,[x17]
        0xb9000230 | (20 // 4) << 10,
        0xb9000230 | (40 // 4) << 10,
        0xb9000230 | (60 // 4) << 10,
        0xa8c147f0, 0xd65f03c0,             # restore, ret
    ]
    return struct.pack('<14I', *words)


def appendix():
    meta = b'KH1BAR-OFF-v2'.ljust(16, b'\0') + bytes.fromhex(INPUT_SHA)
    meta += struct.pack('<10Q', INPUT_SIZE, OUTPUT_SIZE, FLAG, PRODUCER, PRODUCER2,
                        QUAD_CONSTRUCTOR, QUAD_CONSTRUCTOR2, ADAPTER, ADAPTER2, len(QUAD_CALLS))
    assert len(meta) == 128
    data = (meta + adapter()).ljust(0x100, b'\0') + adapter(ADAPTER2, QUAD_CONSTRUCTOR2)
    return data.ljust(0x4000, b'\0')


def payload_header():
    data = appendix()
    assert not any(data[PAYLOAD_SIZE:])
    lines = ['// Generated by dm/tools/kh1_bar_patch.py --emit-header; do not edit.',
             '#pragma once',
             f'static const unsigned char kh1_bar_tail[{PAYLOAD_SIZE}] = {{']
    for offset in range(0, PAYLOAD_SIZE, 16):
        lines.append('  ' + ', '.join(f'0x{x:02x}' for x in data[offset:min(offset+16, PAYLOAD_SIZE)]) + ',')
    lines.append('};')
    lines.append(f'static const unsigned int kh1_bar_calls[{len(QUAD_CALLS)}][2] = {{')
    for site in QUAD_CALLS:
        target = ADAPTER if site in QUAD_CALLS1 else ADAPTER2
        lines.append(f'  {{ 0x{site:08x}, 0x{bl(site, target):08x} }},')
    lines.append('};')
    return '\n'.join(lines) + '\n'


def patch_image(original):
    if len(original) != INPUT_SIZE or hashlib.sha256(original).hexdigest() != INPUT_SHA:
        raise ValueError('requires exact release-reconstructed input SHA/size (no repatching)')
    if original[PRODUCER:PRODUCER+len(PRODUCER_PROLOGUE)] != PRODUCER_PROLOGUE or \
       hashlib.sha256(original[PRODUCER:PRODUCER_END]).hexdigest() != PRODUCER_SHA:
        raise ValueError('persistent bar producer bytes mismatch')
    if original[PRODUCER2:PRODUCER2+len(PRODUCER2_PROLOGUE)] != PRODUCER2_PROLOGUE:
        raise ValueError('live persistent bar producer bytes mismatch')
    if any(original[KEY_PAGE:KEY_PAGE+0x4000]):
        raise ValueError('key page must be zero in file')
    out = bytearray(original)
    for site in QUAD_CALLS:
        constructor = QUAD_CONSTRUCTOR if site in QUAD_CALLS1 else QUAD_CONSTRUCTOR2
        target = ADAPTER if site in QUAD_CALLS1 else ADAPTER2
        expected = bl(site, constructor)
        if struct.unpack_from('<I', original, site)[0] != expected:
            raise ValueError('owned quad BL mismatch')
        struct.pack_into('<I', out, site, bl(site, target))
    return bytes(out) + appendix()


